-- ============================================================================
-- Sistema de gestión de caja y proveedores — Comedores Universitarios
-- Script DDL — PostgreSQL — ESQUEMA REAL (el que construye el backend)
--
-- Este script describe las 8 tablas del sistema tal como las crea Django con
-- `python manage.py migrate`. Sirve para leer la estructura de una vez, revisarla
-- y, si hiciera falta, crearla a mano en una base vacía (por ejemplo en el SQL
-- Editor de Supabase). En el uso normal NO se ejecuta: las tablas las crea
-- `migrate`, que además agrega las tablas internas de Django (ver el final).
--
-- Diferencias respecto del diseño original (docs/02-Diseno-BD-Modulos.md):
--   * usuario: password_hash -> password (formato de Django); activo -> is_active;
--     nuevas columnas last_login, is_superuser e is_staff (las exige el modelo de
--     usuario de Django y el panel /admin/).
--   * Todas las fechas son TIMESTAMPTZ (con zona horaria), no TIMESTAMP.
--   * Los textos opcionales (universidad, dirección, contacto, teléfono, email de
--     proveedor) son NOT NULL con cadena vacía en lugar de NULL.
--   * Restricciones nuevas: una sola caja abierta por sede (índice único parcial),
--     monto de apertura >= 0, monto de comprobante > 0, cantidad >= 1 y precio >= 0
--     en los ítems.
--   * Las claves foráneas no usan ON DELETE CASCADE: el sistema nunca borra
--     comprobantes ni pedidos (las altas y bajas de sedes, usuarios y proveedores
--     son lógicas: activa / is_active / activo = FALSE).
--   * Las columnas con valor por defecto (estado, fechas, activo) las completa el
--     backend; en la base no tienen DEFAULT.
-- ============================================================================

BEGIN;

CREATE TABLE sede (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(150) NOT NULL,
    universidad  VARCHAR(150) NOT NULL,
    direccion    VARCHAR(200) NOT NULL,
    activa       BOOLEAN NOT NULL
);

CREATE TABLE usuario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password       VARCHAR(128) NOT NULL,
    last_login     TIMESTAMPTZ,
    is_superuser   BOOLEAN NOT NULL,
    nombre         VARCHAR(150) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    rol            VARCHAR(20) NOT NULL,
    is_active      BOOLEAN NOT NULL,
    is_staff       BOOLEAN NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL,
    sede_id        BIGINT REFERENCES sede(id) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE caja (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_apertura         TIMESTAMPTZ NOT NULL,
    fecha_cierre           TIMESTAMPTZ,
    monto_apertura         NUMERIC(12,2) NOT NULL,
    monto_cierre_calculado NUMERIC(12,2),
    estado                 VARCHAR(20) NOT NULL,
    sede_id                BIGINT NOT NULL REFERENCES sede(id) DEFERRABLE INITIALLY DEFERRED,
    usuario_id             BIGINT NOT NULL REFERENCES usuario(id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT caja_estado_valido CHECK (estado IN ('abierta', 'cerrada')),
    CONSTRAINT caja_monto_apertura_no_negativo CHECK (monto_apertura >= 0)
);

CREATE TABLE comprobante (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha       TIMESTAMPTZ NOT NULL,
    medio_pago  VARCHAR(20) NOT NULL,
    monto_total NUMERIC(12,2) NOT NULL,
    caja_id     BIGINT NOT NULL REFERENCES caja(id) DEFERRABLE INITIALLY DEFERRED,
    sede_id     BIGINT NOT NULL REFERENCES sede(id) DEFERRABLE INITIALLY DEFERRED,
    usuario_id  BIGINT NOT NULL REFERENCES usuario(id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT comprobante_medio_pago_valido CHECK (medio_pago IN ('efectivo', 'tarjeta', 'transferencia', 'qr')),
    CONSTRAINT comprobante_monto_positivo CHECK (monto_total > 0)
);

CREATE TABLE item_comprobante (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion     VARCHAR(150) NOT NULL,
    cantidad        INTEGER NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    comprobante_id  BIGINT NOT NULL REFERENCES comprobante(id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT item_comprobante_cantidad_valida CHECK (cantidad >= 1),
    CONSTRAINT item_comprobante_precio_no_negativo CHECK (precio_unitario >= 0)
);

CREATE TABLE proveedor (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(150) NOT NULL,
    contacto VARCHAR(150) NOT NULL,
    telefono VARCHAR(50) NOT NULL,
    email    VARCHAR(150) NOT NULL,
    activo   BOOLEAN NOT NULL
);

CREATE TABLE pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_pedido   TIMESTAMPTZ NOT NULL,
    fecha_recibido TIMESTAMPTZ,
    estado         VARCHAR(20) NOT NULL,
    monto_total    NUMERIC(12,2),
    proveedor_id   BIGINT NOT NULL REFERENCES proveedor(id) DEFERRABLE INITIALLY DEFERRED,
    sede_id        BIGINT NOT NULL REFERENCES sede(id) DEFERRABLE INITIALLY DEFERRED,
    usuario_id     BIGINT NOT NULL REFERENCES usuario(id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT pedido_estado_valido CHECK (estado IN ('pendiente', 'recibido', 'cancelado'))
);

CREATE TABLE item_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion     VARCHAR(150) NOT NULL,
    cantidad        INTEGER NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    pedido_id       BIGINT NOT NULL REFERENCES pedido(id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT item_pedido_cantidad_valida CHECK (cantidad >= 1),
    CONSTRAINT item_pedido_precio_no_negativo CHECK (precio_unitario >= 0)
);

-- ============================================================================
-- Índices
-- ============================================================================
-- Una sola caja abierta por sede (índice único parcial)
CREATE UNIQUE INDEX una_caja_abierta_por_sede ON caja (sede_id) WHERE estado = 'abierta';

-- Los del diseño original que se conservaron
CREATE INDEX idx_comprobante_sede_fecha ON comprobante (sede_id, fecha);
CREATE INDEX idx_pedido_proveedor       ON pedido (proveedor_id);
CREATE INDEX idx_pedido_sede_estado     ON pedido (sede_id, estado);

-- Índices sobre claves foráneas (Django los crea solos; acá llevan nombre simple)
CREATE INDEX idx_usuario_sede           ON usuario (sede_id);
CREATE INDEX idx_caja_sede              ON caja (sede_id);
CREATE INDEX idx_caja_usuario           ON caja (usuario_id);
CREATE INDEX idx_comprobante_caja       ON comprobante (caja_id);
CREATE INDEX idx_comprobante_usuario    ON comprobante (usuario_id);
CREATE INDEX idx_item_comprobante_comp  ON item_comprobante (comprobante_id);
CREATE INDEX idx_pedido_sede            ON pedido (sede_id);
CREATE INDEX idx_pedido_usuario         ON pedido (usuario_id);
CREATE INDEX idx_item_pedido_pedido     ON item_pedido (pedido_id);

COMMIT;

